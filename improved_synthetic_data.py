ANNOTATION_RULES = """- Annotate the smallest contiguous phrase that unambiguously denotes the target entity.
- Keep modifiers only when essential to its identity (e.g. offshore wind constructions).
- Interpret mentions in context: energy feedstocks versus natural organisms or habitats.
- Do not annotate infrastructure components, operating parameters, or generic concepts.
- Include method-defining organism/habitat modifiers inside the scientific-method span.
- Do not create overlapping spans. Label all occurrences of the requested label only.
- Keep abbreviations separate from their expanded forms; exclude surrounding parentheses.
- Exclude possessive suffixes and unnecessary punctuation.
- Include connecting words only when essential to one entity (e.g. temporal ranges).
- Use exact, case-sensitive substrings from the sentence as entity text.
- If ambiguous, choose an easier, unambiguous example instead of guessing.
"""

PROMPT = """You are a scientific writer and an expert NER annotator for renewable energy and biodiversity.

Target label: {label}
Definition and boundaries: {definition}

Annotation guidelines:
{rules}

Real reference examples (for annotation style, not copying):
{examples}

Requirements:
- Write exactly one scientifically plausible sentence.
- Follow the target label definition, annotation rules, and reference examples.
- Do not copy or closely paraphrase the examples.
- Include at least one entity belonging to the target label.
- Do not use the label name itself as the entity text.
- Prefer varied entity expressions and sentence structures.
- Never use underscores in the sentence or entity text.
- Copy entity text exactly from the generated sentence.
- Return only entities belonging to the target label.
"""

TOKEN_RE = re.compile(r"\d+(?:\.\d+)+|[^\W\d_]+(?:'[^\W\d_]+)?|\d+|[^\w\s]", re.UNICODE)
THREAD_LOCAL = threading.local()


class Entity(BaseModel):
    text: str
    label: str


class Generation(BaseModel):
    sentence: str
    entities: list[Entity] = Field(min_length=1)


def normalize(text: str) -> str:
    return " ".join(text.casefold().split())


def load_references() -> dict[str, list[dict]]:
    if not reference_dir.is_dir():
        raise FileNotFoundError(f"Reference directory not found: {reference_dir}")

    grouped = defaultdict(list)
    seen = defaultdict(set)
    for path in sorted(reference_dir.iterdir()):
        if path.suffix.lower() not in {".json", ".jsonl"}:
            continue
        content = path.read_text(encoding="utf-8").strip()
        if not content:
            continue
        if path.suffix.lower() == ".jsonl":
            records = [json.loads(line) for line in content.splitlines() if line.strip()]
        else:
            records = json.loads(content)
            if isinstance(records, dict):
                records = [records]
        for record in records:
            sentence = record.get("text", "").strip()
            for entity in record.get("entities", []):
                label, phrase = entity.get("label"), entity.get("text", "")
                if label not in LABEL_GUIDANCE or not sentence or not phrase:
                    continue
                key = (normalize(sentence), normalize(phrase))
                if key not in seen[label]:
                    seen[label].add(key)
                    grouped[label].append({"sentence": sentence, "entity": phrase})

    if not grouped:
        raise ValueError("No annotated references were found")
    return dict(grouped)


def get_client():
    if not hasattr(THREAD_LOCAL, "client"):
        THREAD_LOCAL.client = instructor.from_openai(
            OpenAI(base_url=base_url, api_key="EMPTY", timeout=120),
            mode=instructor.Mode.JSON,
        )
    return THREAD_LOCAL.client


def generate(label: str, references: list[dict], seed: int):
    rng = random.Random(seed)
    samples = rng.sample(references, min(few_shot_sentence_count, len(references)))
    examples = "\n".join(
        f"Sentence: {item['sentence']}\nTarget entity: {item['entity']}"
        for item in samples
    )
    prompt = PROMPT.format(
        label=label,
        definition=LABEL_GUIDANCE[label],
        rules=ANNOTATION_RULES,
        examples=examples,
    )
    response = get_client().chat.completions.create(
        model=model,
        response_model=Generation,
        messages=[{"role": "user", "content": prompt}],
        temperature=temperature,
        max_retries=2,
    )
    return convert(response, label)


def convert(response: Generation, label: str):
    sentence = response.sentence.strip()
    if not sentence or "\n" in sentence or "_" in sentence:
        raise ValueError("Invalid sentence")

    offsets = [(m.group(), m.start(), m.end()) for m in TOKEN_RE.finditer(sentence)]
    entities = []
    for entity in response.entities:
        phrase = entity.text.strip()
        if (entity.label != label or not phrase or "_" in phrase
                or normalize(phrase) == normalize(label.replace("_", " "))):
            continue
        for match in re.finditer(re.escape(phrase), sentence):
            start, end = match.span()
            covered = [i for i, (_, a, b) in enumerate(offsets) if a < end and b > start]
            if not covered or offsets[covered[0]][1] != start or offsets[covered[-1]][2] != end:
                continue
            candidate = {
                "text": phrase,
                "label": label,
                "start_token": covered[0],
                "end_token": covered[-1] + 1,
            }
            if candidate not in entities and not any(
                candidate["start_token"] < other["end_token"]
                and other["start_token"] < candidate["end_token"]
                for other in entities
            ):
                entities.append(candidate)

    if not entities:
        raise ValueError("No valid target entity spans")
    entities.sort(key=lambda item: item["start_token"])
    return {"tokens": [token for token, _, _ in offsets], "entities": entities}, sentence


def main():
    references = load_references()
    labels = sorted(references)
    target = synthetic_entities_per_label * len(labels)
    records, seen_sentences = [], set()
    counts = defaultdict(Counter)
    accepted, rejected = Counter(), Counter()
    rng = random.Random(42)

    def save_records():
        output_file.parent.mkdir(parents=True, exist_ok=True)
        temporary = output_file.with_suffix(output_file.suffix + ".tmp")
        temporary.write_text(json.dumps(records, ensure_ascii=False, indent=2), encoding="utf-8")
        temporary.replace(output_file)

    with ThreadPoolExecutor(max_workers=max_workers) as pool, tqdm(total=target) as bar:
        futures = {}

        def submit(label):
            if accepted[label] >= synthetic_entities_per_label:
                return
            future = pool.submit(generate, label, references[label], rng.getrandbits(64))
            futures[future] = label

        for label in labels:
            for _ in range(2):
                submit(label)

        while futures:
            done, _ = wait(futures, return_when=FIRST_COMPLETED)
            for future in done:
                label = futures.pop(future)
                if accepted[label] >= synthetic_entities_per_label:
                    continue
                try:
                    record, sentence = future.result()
                    key = normalize(sentence)
                    if key in seen_sentences:
                        raise ValueError("Duplicate sentence")
                    mention_counts = Counter(normalize(e["text"]) for e in record["entities"])
                    entity_total = len(record["entities"])
                    remaining = synthetic_entities_per_label - accepted[label]
                    if entity_total > remaining:
                        raise ValueError("Sentence exceeds remaining entity quota")
                    if any(
                        counts[label][phrase] + occurrences > max_entity_occurrences
                        for phrase, occurrences in mention_counts.items()
                    ):
                        raise ValueError("Entity repetition limit reached")
                    seen_sentences.add(key)
                    records.append(record)
                    counts[label].update(mention_counts)
                    accepted[label] += entity_total
                    bar.update(entity_total)
                except Exception:
                    rejected[label] += 1
                submit(label)

    missing = {
        label: synthetic_entities_per_label - accepted[label]
        for label in labels
        if accepted[label] < synthetic_entities_per_label
    }
    if missing:
        raise RuntimeError(f"Generation incomplete: {missing}")

    actual_counts = Counter(
        entity["label"] for record in records for entity in record["entities"]
    )
    for label in labels:
        if actual_counts[label] != synthetic_entities_per_label:
            raise RuntimeError(
                f"Saved annotation mismatch for {label}: {actual_counts[label]}"
            )
    if output_file.exists():
        raise FileExistsError(f"Output file already exists: {output_file}")
    save_records()
    print(f"Saved {len(records)} sentences to {output_file}")
    for label in labels:
        print(f"{label}: accepted_entities={accepted[label]}, rejected={rejected[label]}, unique_entities={len(counts[label])}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--synthetic_entities_per_label", "--synthetic_examples_per_label",
                        type=int, default=synthetic_entities_per_label)
    parser.add_argument("--temperature", type=float, default=temperature)
    parser.add_argument("--few_shot_sentence_count", type=int, default=few_shot_sentence_count)
    parser.add_argument("--max_entity_occurrences", type=int, default=max_entity_occurrences)
    parser.add_argument("--output_file", type=Path, default=output_file)
    args = parser.parse_args()

    synthetic_entities_per_label = args.synthetic_entities_per_label
    temperature = args.temperature
    few_shot_sentence_count = args.few_shot_sentence_count
    max_entity_occurrences = args.max_entity_occurrences
    output_file = Path("data/local/ner") / args.output_file.name
    main()
